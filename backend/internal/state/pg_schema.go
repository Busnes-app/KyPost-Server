package state

import "github.com/Busnes-app/kypost-server/backend/internal/dbbackend"

// pgSchema is schema on Postgres, with every additive column in place: column names match
// SQLite's exactly (the migration and backup copies compare them), BIGINT for INTEGER,
// BYTEA for BLOB, an identity for AUTOINCREMENT and a rowid identity where the SQL orders
// by rowid. Later columns are ADD COLUMN IF NOT EXISTS here; dbbackend reruns this DDL
// when it changes.
const pgSchema = `
CREATE TABLE IF NOT EXISTS backup_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at TEXT NOT NULL, action TEXT NOT NULL,
 actor TEXT NOT NULL, target TEXT NOT NULL, outcome TEXT NOT NULL, details TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS processed (message_id TEXT PRIMARY KEY, seen_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS processed_seen_at ON processed(seen_at);
CREATE TABLE IF NOT EXISTS decisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 message_id TEXT NOT NULL DEFAULT '', sender TEXT NOT NULL DEFAULT '', sent_to TEXT NOT NULL DEFAULT '',
 subject TEXT NOT NULL DEFAULT '', label TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT '',
 detail TEXT NOT NULL DEFAULT '', at_utc TEXT NOT NULL DEFAULT '', at_unix BIGINT);
CREATE INDEX IF NOT EXISTS decisions_at_unix ON decisions(at_unix);
CREATE INDEX IF NOT EXISTS decisions_message_id ON decisions(message_id);
CREATE TABLE IF NOT EXISTS notifications (
 endpoint TEXT PRIMARY KEY, auth TEXT NOT NULL DEFAULT '', p256dh TEXT NOT NULL DEFAULT '',
 user_agent TEXT NOT NULL DEFAULT '', updated_at TEXT NOT NULL DEFAULT '', seq BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS native_devices (
 device_id TEXT PRIMARY KEY, platform TEXT NOT NULL DEFAULT '', push_token TEXT NOT NULL DEFAULT '',
 device_name TEXT NOT NULL DEFAULT '', app_version TEXT NOT NULL DEFAULT '', user_agent TEXT NOT NULL DEFAULT '',
 registered_at TEXT NOT NULL DEFAULT '', updated_at TEXT NOT NULL DEFAULT '', user_id TEXT NOT NULL DEFAULT '',
 mfa_approver BIGINT NOT NULL DEFAULT 0, transport TEXT NOT NULL DEFAULT '', secret_hash TEXT NOT NULL DEFAULT '',
 seq BIGINT NOT NULL,
 enrollment_public_key TEXT NOT NULL DEFAULT '', enrollment_key_at TEXT NOT NULL DEFAULT '',
 enrollment_envelope_versions TEXT NOT NULL DEFAULT '[]', encryption_enrolled BIGINT NOT NULL DEFAULT 0,
 enrolled_version BIGINT NOT NULL DEFAULT 0, enrolled_generation BIGINT NOT NULL DEFAULT 0,
 enrolled_fingerprint TEXT NOT NULL DEFAULT '', p256dh TEXT NOT NULL DEFAULT '', auth TEXT NOT NULL DEFAULT '');
CREATE INDEX IF NOT EXISTS native_devices_push ON native_devices(push_token, platform);
CREATE TABLE IF NOT EXISTS pull_notifications (
 seq BIGINT PRIMARY KEY, title TEXT NOT NULL DEFAULT '', body TEXT NOT NULL DEFAULT '',
 data TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT '', device_ids TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS deferrals (
 message_id TEXT PRIMARY KEY, attempts BIGINT NOT NULL DEFAULT 0, first_at BIGINT NOT NULL, last_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS deferrals_first_at ON deferrals(first_at);
CREATE TABLE IF NOT EXISTS sorter_predictions (
 message_id TEXT PRIMARY KEY, check_hash TEXT NOT NULL, model TEXT NOT NULL, vec BYTEA NOT NULL,
 predicted TEXT NOT NULL, at_unix BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS sorter_predictions_at ON sorter_predictions(at_unix);
CREATE TABLE IF NOT EXISTS sorter_corrections (
 message_id TEXT PRIMARY KEY, label TEXT NOT NULL, model TEXT NOT NULL, vec BYTEA NOT NULL, at_unix BIGINT NOT NULL,
 -- SQLite's implicit rowid, which the sorter orders by.
 rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE);
CREATE INDEX IF NOT EXISTS sorter_corrections_label ON sorter_corrections(label, at_unix);
CREATE TABLE IF NOT EXISTS scheduled_sends (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL, mailbox TEXT NOT NULL, send_at BIGINT NOT NULL,
 status TEXT NOT NULL, reason TEXT NOT NULL DEFAULT '', sealed BYTEA, summary BYTEA NOT NULL,
 next_attempt BIGINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL, returning_since BIGINT NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS scheduled_sends_due ON scheduled_sends(status, send_at);
CREATE INDEX IF NOT EXISTS scheduled_sends_user ON scheduled_sends(user_id, status);
CREATE TABLE IF NOT EXISTS send_ledger (id TEXT PRIMARY KEY, user_id TEXT NOT NULL, at BIGINT NOT NULL, recipients BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS send_ledger_user ON send_ledger(user_id, at);
CREATE TABLE IF NOT EXISTS snoozes (
 message_id TEXT PRIMARY KEY, wake_at BIGINT NOT NULL, inbox_id TEXT NOT NULL DEFAULT '', woken_at BIGINT NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS snoozes_wake ON snoozes(woken_at, wake_at);
CREATE TABLE IF NOT EXISTS agent_tokens (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL, label TEXT NOT NULL, hash TEXT NOT NULL, scope TEXT NOT NULL,
 created_at BIGINT NOT NULL, last_used_at BIGINT NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS agent_tokens_user ON agent_tokens(user_id);
CREATE TABLE IF NOT EXISTS ooo_messages (message_key TEXT PRIMARY KEY, at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS ooo_senders (sender TEXT PRIMARY KEY, period TEXT NOT NULL, at BIGINT NOT NULL);
`

// Kind is the catalog kind of a state.db.
const Kind = "state"

func init() {
	dbbackend.Register(dbbackend.Kind{Name: Kind, File: "state.db", DDL: pgSchema, CreateSQLite: createSQLite})
}

// createSQLite creates or brings up to date the SQLite state database at path, as an
// open does, for the migration and backup copies.
func createSQLite(path string) error {
	db, err := openSQLiteDB(path, "")
	if err != nil {
		return err
	}
	return db.Close()
}
