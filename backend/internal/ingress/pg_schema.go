package ingress

import (
	"os"
	"path/filepath"

	"github.com/Busnes-app/kypost-server/backend/internal/dbbackend"
)

// pgSchema is schema plus archivedSchema on Postgres, column names as on SQLite: BIGINT
// for INTEGER, BYTEA for BLOB, and a rowid identity on deliveries, which the SQL pages by.
const pgSchema = `
CREATE TABLE IF NOT EXISTS limits (id BIGINT PRIMARY KEY CHECK(id=1), message_bytes BIGINT, payload_bytes BIGINT, records BIGINT);
CREATE TABLE IF NOT EXISTS routes (address TEXT PRIMARY KEY, issuer TEXT NOT NULL, subject TEXT NOT NULL, mailbox TEXT NOT NULL, generation BIGINT NOT NULL, active BIGINT NOT NULL, valid_until BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS deliveries (gateway TEXT NOT NULL, id TEXT NOT NULL, sender TEXT NOT NULL, created BIGINT NOT NULL, digest TEXT NOT NULL DEFAULT '', raw BYTEA, state TEXT NOT NULL DEFAULT 'staged', lease TEXT NOT NULL DEFAULT '', lease_until BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(gateway,id),
 rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE);
CREATE TABLE IF NOT EXISTS bindings (gateway TEXT NOT NULL, id TEXT NOT NULL, address TEXT NOT NULL, issuer TEXT NOT NULL, subject TEXT NOT NULL, mailbox TEXT NOT NULL, generation BIGINT NOT NULL, PRIMARY KEY(gateway,id,address), FOREIGN KEY(gateway,id) REFERENCES deliveries(gateway,id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS archived (gateway TEXT NOT NULL, id TEXT NOT NULL, sender TEXT NOT NULL, digest TEXT NOT NULL, recipients TEXT NOT NULL, archived_at BIGINT NOT NULL, disposition TEXT NOT NULL CHECK(disposition IN ('imported','released','discarded','partially_released')), PRIMARY KEY(gateway,id));
CREATE INDEX IF NOT EXISTS imported ON deliveries(gateway,id) WHERE state='imported';
`

// Kind is the catalog kind of an ingress.db.
const Kind = "ingress"

func init() {
	dbbackend.Register(dbbackend.Kind{Name: Kind, File: "ingress.db", DDL: pgSchema, CreateSQLite: createSQLite})
}

// createSQLite creates or brings up to date the SQLite ingress database at path for the
// copies, keeping an existing file's own limits.
func createSQLite(path string) error {
	limits, existing := ReceivingLimits, false
	if _, err := os.Lstat(path); err == nil {
		existing = true
		db, err := dbbackend.OpenSQLiteFile(path, "mode=ro")
		if err != nil {
			return err
		}
		err = db.QueryRow("SELECT message_bytes,payload_bytes,records FROM limits WHERE id=1").Scan(&limits.MessageBytes, &limits.PayloadBytes, &limits.Records)
		_ = db.Close()
		if err != nil {
			return err
		}
	}
	s, err := openStore(filepath.Dir(path), limits, existing, false)
	if err != nil {
		return err
	}
	return s.Close()
}

// pick is the SQLite or the Postgres text of a statement for the store's backend.
func pick(pg bool, sqlite, postgres string) string {
	if pg {
		return postgres
	}
	return sqlite
}
