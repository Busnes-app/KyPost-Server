// Package volumes owns the table-mode volume stores. Ordinary single-tenant installs
// never create this database. SQLite is used only for authenticated capsule copies.
package volumes

import (
	"database/sql"
	"errors"
	"fmt"
	"net/url"
	"os"
	"path/filepath"

	"github.com/Busnes-app/kypost-server/backend/internal/dbbackend"
	_ "modernc.org/sqlite"
)

const (
	File = "volumes.db"
	Kind = "volumes"
)

const sqliteSchema = `
CREATE TABLE IF NOT EXISTS documents (
 root TEXT NOT NULL, path TEXT NOT NULL, owner TEXT, revision INTEGER NOT NULL, body BLOB NOT NULL, updated_at INTEGER NOT NULL,
 PRIMARY KEY(root, path),
 CHECK(root IN ('config','state') AND length(CAST(path AS BLOB)) BETWEEN 1 AND 512 AND path NOT LIKE '/%' AND path NOT LIKE '%/'
  AND path NOT LIKE '%//%' AND '/' || path || '/' NOT LIKE '%/../%' AND '/' || path || '/' NOT LIKE '%/./%'
  AND (owner IS NULL OR owner <> '')));
CREATE TABLE IF NOT EXISTS doc_keys (org_id TEXT PRIMARY KEY, wrapped BLOB NOT NULL, created_at INTEGER NOT NULL);
`

const pgSchema = `
CREATE TABLE IF NOT EXISTS documents (
 root TEXT NOT NULL, path TEXT NOT NULL, owner TEXT, revision BIGINT GENERATED BY DEFAULT AS IDENTITY, body BYTEA NOT NULL,
 updated_at BIGINT NOT NULL, PRIMARY KEY(root, path),
 CHECK(root IN ('config','state') AND octet_length(path) BETWEEN 1 AND 512 AND path NOT LIKE '/%' AND path NOT LIKE '%/'
  AND path NOT LIKE '%//%' AND '/' || path || '/' NOT LIKE '%/../%' AND '/' || path || '/' NOT LIKE '%/./%'
  AND (owner IS NULL OR owner <> '')));
CREATE TABLE IF NOT EXISTS doc_keys (org_id TEXT PRIMARY KEY, wrapped BYTEA NOT NULL, created_at BIGINT NOT NULL);
`

func init() {
	dbbackend.Register(dbbackend.Kind{Name: Kind, File: File, DDL: pgSchema, CreateSQLite: func(path string) error {
		db, err := openSQLite(path, true)
		if err == nil {
			err = db.Close()
		}
		return err
	}})
}

// Open opens the shared documents. create is used only by a new table-mode install or
// the offline migration. An existing-only open never creates a missing database.
func Open(stateDir string, create bool) (*sql.DB, error) {
	path := filepath.Join(stateDir, File)
	pg := dbbackend.Postgres()
	if !create {
		held, err := dbbackend.Held(path)
		if err != nil {
			return nil, err
		}
		pg = held
	}
	if !pg {
		return openSQLite(path, create)
	}
	db, err := dbbackend.Open(path, dbbackend.Options{Kind: Kind, DDL: pgSchema, Create: create})
	if errors.Is(err, dbbackend.ErrNotFound) {
		return nil, fmt.Errorf("%w: volumes store", os.ErrNotExist)
	}
	return db, err
}

func openSQLite(path string, create bool) (*sql.DB, error) {
	abs, err := filepath.Abs(path)
	if err != nil {
		return nil, err
	}
	if !create {
		if _, err := os.Lstat(abs); err != nil {
			return nil, err
		}
	}
	mode := "rw"
	if create {
		mode = "rwc"
	}
	db, err := sql.Open("sqlite", (&url.URL{Scheme: "file", Path: abs}).String()+
		"?mode="+mode+"&_txlock=immediate&_pragma=journal_mode(WAL)&_pragma=busy_timeout(5000)&_pragma=foreign_keys(ON)")
	if err != nil {
		return nil, err
	}
	if _, err := db.Exec(sqliteSchema); err != nil {
		_ = db.Close()
		return nil, err
	}
	return db, nil
}
