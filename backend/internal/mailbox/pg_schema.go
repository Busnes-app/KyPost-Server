package mailbox

import (
	"os"
	"path/filepath"

	"github.com/Busnes-app/kypost-server/backend/internal/dbbackend"
)

// pgSchema is schema plus reference_generation on Postgres. Column names match SQLite's
// (the copies compare them): BIGINT for INTEGER, BYTEA for BLOB, CITEXT for COLLATE
// NOCASE on a C-locale database, an identity for AUTOINCREMENT, referenced tables first.
// The usage triggers are row-level plpgsql with the same arithmetic; their bodies name
// tables unqualified, so they act on the schema of the session's search_path, which is
// always the store's own.
const pgSchema = `
CREATE TABLE IF NOT EXISTS identity (id BIGINT PRIMARY KEY CHECK(id=1), issuer TEXT NOT NULL, subject TEXT NOT NULL, mailbox TEXT NOT NULL, message_bytes BIGINT NOT NULL, payload_bytes BIGINT NOT NULL, records BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS namespace (id BIGINT PRIMARY KEY CHECK(id=1), token TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS reference_generation (id BIGINT PRIMARY KEY CHECK(id=1), token TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS folders (name TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS labels (name CITEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS messages (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, folder TEXT NOT NULL REFERENCES folders(name), raw BYTEA, digest TEXT NOT NULL, sender TEXT NOT NULL, subject TEXT NOT NULL, sent_to TEXT NOT NULL, cc TEXT NOT NULL, bcc TEXT NOT NULL, at_utc TEXT NOT NULL, seen BIGINT NOT NULL DEFAULT 0, starred BIGINT NOT NULL DEFAULT 0, draft BIGINT NOT NULL DEFAULT 0, labels TEXT NOT NULL DEFAULT '[]');
CREATE INDEX IF NOT EXISTS message_folder_ids ON messages(folder,id) WHERE raw IS NOT NULL;
CREATE INDEX IF NOT EXISTS message_folder_digests ON messages(folder,digest) WHERE raw IS NOT NULL;
CREATE TABLE IF NOT EXISTS incoming_replacements (source_id BIGINT PRIMARY KEY REFERENCES messages(id), marker TEXT NOT NULL UNIQUE, source_hash TEXT NOT NULL, ciphertext_hash TEXT NOT NULL, replacement_id BIGINT NOT NULL UNIQUE REFERENCES messages(id));
CREATE TABLE IF NOT EXISTS imported (message_id BIGINT PRIMARY KEY REFERENCES messages(id));
CREATE TABLE IF NOT EXISTS receipts (gateway TEXT NOT NULL, delivery TEXT NOT NULL, envelope TEXT NOT NULL, digest TEXT NOT NULL, message_id BIGINT NOT NULL REFERENCES messages(id), PRIMARY KEY(gateway,delivery));
CREATE TABLE IF NOT EXISTS changes (revision BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, message_id BIGINT NOT NULL, folder TEXT NOT NULL, removed BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS usage (id BIGINT PRIMARY KEY CHECK(id=1), records BIGINT NOT NULL, payload_bytes BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS outbox (id TEXT PRIMARY KEY, ciphertext BYTEA NOT NULL, sent_bytes BIGINT NOT NULL, sent_reserved BIGINT NOT NULL, sent_id BIGINT REFERENCES messages(id), created_at BIGINT NOT NULL DEFAULT (floor(extract(epoch from statement_timestamp()))::bigint));
CREATE TABLE IF NOT EXISTS outbox_independent (job TEXT PRIMARY KEY REFERENCES outbox(id));
CREATE TABLE IF NOT EXISTS outbox_deliveries (job TEXT NOT NULL REFERENCES outbox(id), sequence BIGINT NOT NULL, state TEXT NOT NULL CHECK(state IN ('queued','submitting','accepted','retryable','failed','uncertain','quarantined')), claim TEXT NOT NULL DEFAULT '', attempts BIGINT NOT NULL DEFAULT 0, next_attempt BIGINT NOT NULL DEFAULT 0, PRIMARY KEY(job,sequence));

CREATE OR REPLACE FUNCTION outbox_insert() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 UPDATE usage SET records=records+1+NEW.sent_reserved,payload_bytes=payload_bytes+length(NEW.ciphertext)+NEW.sent_bytes WHERE id=1; RETURN NULL; END $$;
CREATE OR REPLACE TRIGGER outbox_insert AFTER INSERT ON outbox FOR EACH ROW EXECUTE FUNCTION outbox_insert();
CREATE OR REPLACE FUNCTION outbox_update() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 UPDATE usage SET records=records+NEW.sent_reserved-OLD.sent_reserved,payload_bytes=payload_bytes+length(NEW.ciphertext)-length(OLD.ciphertext)+NEW.sent_bytes-OLD.sent_bytes WHERE id=1; RETURN NULL; END $$;
CREATE OR REPLACE TRIGGER outbox_update AFTER UPDATE ON outbox FOR EACH ROW EXECUTE FUNCTION outbox_update();
CREATE OR REPLACE FUNCTION outbox_delivery_insert() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 UPDATE usage SET records=records+1 WHERE id=1; RETURN NULL; END $$;
CREATE OR REPLACE TRIGGER outbox_delivery_insert AFTER INSERT ON outbox_deliveries FOR EACH ROW EXECUTE FUNCTION outbox_delivery_insert();
CREATE OR REPLACE FUNCTION mailbox_insert() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 UPDATE usage SET records=records+1,payload_bytes=payload_bytes+coalesce(length(NEW.raw),0) WHERE id=1; RETURN NULL; END $$;
CREATE OR REPLACE TRIGGER mailbox_insert AFTER INSERT ON messages FOR EACH ROW EXECUTE FUNCTION mailbox_insert();
CREATE OR REPLACE FUNCTION mailbox_raw_update() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 UPDATE usage SET payload_bytes=payload_bytes-coalesce(length(OLD.raw),0)+coalesce(length(NEW.raw),0) WHERE id=1; RETURN NULL; END $$;
CREATE OR REPLACE TRIGGER mailbox_raw_update AFTER UPDATE OF raw ON messages FOR EACH ROW EXECUTE FUNCTION mailbox_raw_update();
CREATE OR REPLACE FUNCTION mailbox_delete() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 UPDATE usage SET records=records-1,payload_bytes=payload_bytes-coalesce(length(OLD.raw),0) WHERE id=1; RETURN NULL; END $$;
CREATE OR REPLACE TRIGGER mailbox_delete AFTER DELETE ON messages FOR EACH ROW EXECUTE FUNCTION mailbox_delete();
CREATE TABLE IF NOT EXISTS bodies (message_id BIGINT PRIMARY KEY REFERENCES messages(id), object TEXT NOT NULL UNIQUE, size BIGINT NOT NULL, sha256 BYTEA NOT NULL);
CREATE TABLE IF NOT EXISTS body_tombstones (object TEXT PRIMARY KEY, at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS body_orphans (object TEXT PRIMARY KEY, seen_at BIGINT NOT NULL);
CREATE OR REPLACE FUNCTION body_insert() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 UPDATE usage SET payload_bytes=payload_bytes+NEW.size WHERE id=1; RETURN NULL; END $$;
CREATE OR REPLACE TRIGGER body_insert AFTER INSERT ON bodies FOR EACH ROW EXECUTE FUNCTION body_insert();
CREATE OR REPLACE FUNCTION body_update() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 UPDATE usage SET payload_bytes=payload_bytes-OLD.size+NEW.size WHERE id=1; RETURN NULL; END $$;
CREATE OR REPLACE TRIGGER body_update AFTER UPDATE OF size ON bodies FOR EACH ROW EXECUTE FUNCTION body_update();
CREATE OR REPLACE FUNCTION body_delete() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 UPDATE usage SET payload_bytes=payload_bytes-OLD.size WHERE id=1; RETURN NULL; END $$;
CREATE OR REPLACE TRIGGER body_delete AFTER DELETE ON bodies FOR EACH ROW EXECUTE FUNCTION body_delete();
`

// Kind is the catalog kind of a mailbox.db.
const Kind = "mailbox"

func init() {
	dbbackend.Register(dbbackend.Kind{Name: Kind, File: "mailbox.db", DDL: pgSchema, CreateSQLite: createSQLite})
}

// createSQLite creates or brings up to date the SQLite mailbox database at path for the
// copies. A new file gets a placeholder identity the copy replaces; an existing one
// keeps its own, which an ordinary open requires.
func createSQLite(path string) error {
	dir := filepath.Dir(path)
	owner, limits := Owner{Issuer: "copy", Subject: "copy", Mailbox: "copy"}, Limits{MessageBytes: 1, PayloadBytes: 1, Records: 1}
	if _, err := os.Lstat(path); err == nil {
		db, err := openSQLite(path, "mode=ro")
		if err != nil {
			return err
		}
		err = db.QueryRow("SELECT issuer,subject,mailbox,message_bytes,payload_bytes,records FROM identity WHERE id=1").Scan(&owner.Issuer, &owner.Subject, &owner.Mailbox, &limits.MessageBytes, &limits.PayloadBytes, &limits.Records)
		_ = db.Close()
		if err != nil {
			return err
		}
	}
	s, err := openSQLiteStore(dir, owner, limits, "")
	if err != nil {
		return err
	}
	return s.Close()
}

// pick is the SQLite or the Postgres text of a statement for the store's backend.
func pick(pg bool, sqlite, postgres string) string {
	if pg {
		return postgres
	}
	return sqlite
}
